#!/usr/bin/env python3
"""Generate ``docs/COMMANDS.md`` from the live command registry.

Documentation that is written by hand drifts. This script imports HAVOC with a
throwaway configuration, renders every registered command from the locale
catalog, and writes a Markdown reference. ``--check`` fails when the committed
file is stale, which is what CI runs.

Usage::

    python scripts/generate_docs.py          # write docs/COMMANDS.md
    python scripts/generate_docs.py --check  # verify it is up to date
"""

from __future__ import annotations

import argparse
import asyncio
import logging
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from havoc.config import Config  # noqa: E402
from havoc.runtime import Runtime  # noqa: E402

TARGET = ROOT / "docs" / "COMMANDS.md"

CATEGORY_TITLES = {
    "core": "Core",
    "language": "Language & text",
    "utilities": "Utilities",
    "scheduling": "Scheduling & time",
    "information": "Information",
    "profile": "Profile",
    "messaging": "Messaging",
    "detection": "Detection & automation",
    "persona": "Persona",
    "media": "Media",
    "management": "Management",
    "fun": "Fun",
}

HEADER = """# Command reference

<!-- Generated by scripts/generate_docs.py — do not edit by hand. -->

Every command is available in English and Farsi; the description shown here is
the English catalog text. Commands marked **owner only** are refused for any
account other than the logged-in user.

`{prefix}` in the usage column stands for the active prefix (default `.`).
"""


async def render() -> str:
    tmp = Path(tempfile.mkdtemp())
    config = Config(
        api_id=1,
        api_hash="0" * 32,
        data_dir=tmp,
        database_path=tmp / "docs.db",
        log_dir=tmp / "logs",
        backup_dir=tmp / "backups",
        plugin_dir=tmp / "plugins",
        session_path=tmp / "session",
    )
    logger = logging.getLogger("havoc.docs")
    logger.setLevel(logging.CRITICAL)
    runtime = await Runtime.create(config, logger)
    runtime.load_features()
    try:
        locales = runtime.locales
        prefix = runtime.prefix
        lines = [HEADER.format(prefix=prefix)]
        lines.append(f"\nTotal: **{len(runtime.registry.visible())} commands**.\n")
        for category, commands in sorted(runtime.registry.by_category().items()):
            title = CATEGORY_TITLES.get(category, category.title())
            lines.append(f"\n## {title}\n")
            lines.append("| Command | Description | Usage | Aliases |")
            lines.append("| --- | --- | --- | --- |")
            for command in sorted(commands, key=lambda c: c.name):
                description = locales.raw(command.description_key, "en") or command.description or ""
                usage = locales.raw(command.usage_key, "en") or command.usage or ""
                usage_cell = f"`{prefix}{command.name} {usage}`".replace(" `", "`").strip() if usage else f"`{prefix}{command.name}`"
                aliases = ", ".join(f"`{prefix}{alias}`" for alias in command.aliases) or "—"
                flags = []
                if command.owner_only:
                    flags.append("owner only")
                if command.changes_state:
                    flags.append("changes state")
                if command.needs_confirmation:
                    flags.append("asks for confirmation")
                if command.requires_reply:
                    flags.append("reply required")
                if command.feature:
                    flags.append(f"feature `{command.feature}`")
                if flags:
                    description = description.rstrip(".") + " _(" + "; ".join(flags) + ")._"
                lines.append(f"| `{prefix}{command.name}` | {description} | {usage_cell} | {aliases} |")
        lines.append("")
        lines.append("## Notes\n")
        lines.append("- Automation features are **off by default**; enable them with `.feature <name> on`.")
        lines.append("- `--yes` skips the confirmation prompt for state-changing commands.")
        lines.append("- Dry-run (`.dryrun on`) previews state-changing commands without applying them.")
        lines.append("- The emergency stop (`.stop`) freezes commands, automation and scheduled work.")
        return "\n".join(lines) + "\n"
    finally:
        await runtime.db.close()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when the committed file is stale")
    args = parser.parse_args(argv)

    content = asyncio.run(render())
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != content:
            print(f"docs are stale: run 'python {Path(__file__).name}'", file=sys.stderr)
            return 1
        print(f"docs OK: {TARGET.relative_to(ROOT)}")
        return 0

    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(content, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
